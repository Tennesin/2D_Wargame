# ==========================================
# УГЛОВОЙ СЕКТОР НАВОДКИ (УГН) В ЗАВИСИМОСТИ ОТ КАЛИБРА
# ==========================================
TD_ARC_MAX_DEG = 50.0          # полный сектор у минимального калибра (±25°)
TD_ARC_MIN_DEG = 10.0          # полный сектор у максимального калибра (±5°)
TD_ARC_CURVE = 1.0             # 1 = линейно; >1 долго держит широкий сектор, потом резко сужает; <1 наоборот

def gun_arc_deg(cal):
    """Полный сектор наводки, градусы, кратный 2° (чтобы «±» выводился целым числом)."""
    t = clamp((cal - CALIBER.min) / (CALIBER.max - CALIBER.min), 0.0, 1.0) ** TD_ARC_CURVE
    return 2.0 * round(lerp(TD_ARC_MAX_DEG, TD_ARC_MIN_DEG, t) / 2.0)

