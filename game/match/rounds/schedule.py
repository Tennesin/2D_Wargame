"""game/match/rounds/schedule.py — правила раундов: сколько врагов и какой бюджет у каждого.
Без pygame и без знания об игре: чистые данные и функции."""

ROUND_TIME_S = 45.0     # раунд закрывается по времени, если игрок не добил состав
COUNTDOWN_S = 3.0       # отсчёт перед появлением группы
MAX_BOTS = 8            # больше ботов на карте одновременно быть не может

# Стадии по порядку: (число врагов, доли бюджета игрока по раундам стадии).
# Последняя стадия повторяется бесконечно: на ней берётся последняя доля.
STAGES = (
    (1, (0.75, 1.00)),
    (2, (0.40, 0.50, 0.60, 0.70)),
    (3, (0.35, 0.45, 0.60, 0.70, 0.80, 0.90)),
    (4, (0.70, 0.85, 1.00,)),
)

def round_budgets(n):
    """Номер раунда (с 1) -> список долей бюджета игрока, по одной на каждого врага."""
    i = max(1, n) - 1
    for count, fracs in STAGES[:-1]:
        if i < len(fracs):
            return [fracs[i]] * count
        i -= len(fracs)
    count, fracs = STAGES[-1]
    return [fracs[min(i, len(fracs) - 1)]] * count