# ==========================================
# 1. ВХОДНЫЕ ПАРАМЕТРЫ (то, что крутят ползунки)
# ==========================================
@dataclass(frozen=True)
class Param:
    label: str       # подпись на панели
    unit: str        # единица измерения
    min: float
    max: float
    default: float   # стартовое значение
    step: float      # шаг ползунка

